import sharp from 'sharp';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';

await mkdir('public/images/backgrounds', { recursive: true });

// Full-bleed backgrounds are exported at quality 88: lossy WebP keeps the
// gradients clean while cutting the payload by ~90% versus lossless. The mean
// absolute error check below still guards against a bad encode.
async function encode(input, output, { quality, width } = {}) {
  let source = sharp(input);
  let reference;
  if (width) {
    const resized = await sharp(input)
      .resize({ width, withoutEnlargement: true })
      .png()
      .toBuffer();
    source = sharp(resized);
    reference = resized;
  }
  await source
    .webp({ quality, effort: 6, smartSubsample: true })
    .toFile(output);
  const a = await sharp(reference ?? input)
    .ensureAlpha()
    .raw()
    .toBuffer();
  const b = await sharp(output).ensureAlpha().raw().toBuffer();
  assert.equal(a.length, b.length, `${output}: dimension mismatch`);
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff += Math.abs(a[i] - b[i]);
  const mae = diff / a.length;
  assert.ok(mae < 5, `${output}: MAE ${mae.toFixed(2)} exceeds tolerance`);
  return mae;
}

// The homepage hero is generated by scripts/generate-hero-layers.mjs and the
// footer by scripts/generate-footer-background.mjs (it also derives the phone
// portrait variant); this script covers the remaining full-bleed backgrounds.
for (const [source, name] of [['hitam bintang', 'stars']]) {
  const mae = await encode(
    `assets/background/hd/${source}.png`,
    `public/images/backgrounds/${name}.webp`,
    { quality: 88 },
  );
  console.log(`${name}: webp q88 (MAE ${mae.toFixed(2)})`);
}

// Recruitment hero: Figma node 1436:3506 carries a 1672x941 IMAGE fill that is
// cropped by its imageTransform (scaleX .8975 / tx .05126, scaleY .9590) and
// stretched to the 1440x866 frame. Bake the crop verbatim — the reference node
// has no colour overlay, so none is applied.
{
  const source =
    'assets/assets recruitment page/hero section/recruitment-hero-fill-raw.png';
  const cropped = await sharp(source)
    .extract({ left: 86, top: 0, width: 1500, height: 902 })
    .resize(1440, 866)
    .png()
    .toBuffer();
  await sharp(cropped)
    .webp({ quality: 88, effort: 6, smartSubsample: true })
    .toFile('public/images/backgrounds/recruitment.webp');
  const a = await sharp(cropped).ensureAlpha().raw().toBuffer();
  const b = await sharp('public/images/backgrounds/recruitment.webp')
    .ensureAlpha()
    .raw()
    .toBuffer();
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff += Math.abs(a[i] - b[i]);
  console.log(`recruitment: webp q88 (MAE ${(diff / a.length).toFixed(2)})`);
}

// The old role exports contained titles/buttons. These are artwork-only fills,
// re-encoded from the pristine card art in assets/image-src when available.
for (const id of ['data', 'core', 'language', 'vision', 'product', 'growth']) {
  for (const width of [1280, 2560]) {
    const pristine = `assets/image-src/hods/card-${id}.webp`;
    const source = existsSync(pristine)
      ? pristine
      : `public/images/hods/card-${id}.webp`;
    const mae = await encode(
      source,
      `public/images/roles/role-${id}-${width}.webp`,
      { quality: 88, width },
    );
    console.log(`role-${id}-${width}: webp q88 (MAE ${mae.toFixed(2)})`);
  }
}
